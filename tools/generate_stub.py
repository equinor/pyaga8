"""Generate the type stub ``pyaga8.pyi`` from the built extension module.

The docstrings in the stub are copied from the runtime docstrings, which come from the Rust
doc comments in ``src/lib.rs``. The type annotations are listed explicitly below, because the
compiled module does not carry them.

Usage (after ``maturin develop``)::

    python tools/generate_stub.py          # rewrite pyaga8.pyi
    python tools/generate_stub.py --check  # exit 1 if pyaga8.pyi is out of date

``tests/test_stub.py`` runs the same check.
"""

import argparse
import inspect
import sys
from pathlib import Path

import pyaga8

STUB_PATH = Path(__file__).resolve().parents[1] / "pyaga8.pyi"

CLASSES = ["Gerg2008", "Detail", "Composition"]

# Parameter and return annotations of the methods. Every method of the extension classes must
# be listed here, otherwise generation fails.
METHOD_TYPES = {
    ("Gerg2008", "calc_density"): ({"flag": "int"}, "None"),
    ("Detail", "calc_density"): ({}, "None"),
    ("Gerg2008", "calc_pressure"): ({}, "float"),
    ("Detail", "calc_pressure"): ({}, "float"),
    ("Gerg2008", "calc_properties"): ({}, "None"),
    ("Detail", "calc_properties"): ({}, "None"),
    ("Gerg2008", "calc_molar_mass"): ({}, "None"),
    ("Detail", "calc_molar_mass"): ({}, "None"),
    ("Gerg2008", "set_composition"): ({"comp": "Composition"}, "None"),
    ("Detail", "set_composition"): ({"comp": "Composition"}, "None"),
}

# Properties of Gerg2008 and Detail that can be assigned in addition to being read.
READ_WRITE_PROPERTIES = {"pressure", "temperature", "d"}

HEADER = '''"""Type stub for the pyaga8 extension module.

Generated by tools/generate_stub.py from the runtime docstrings (Rust doc comments in
src/lib.rs). Do not edit by hand; tests/test_stub.py checks that it is up to date.
"""

__version__: str
'''


def format_docstring(doc, indent):
    """Return ``doc`` as an indented triple-quoted docstring block (list of lines)."""
    lines = inspect.cleandoc(doc).splitlines()
    pad = " " * indent
    if len(lines) == 1:
        return [f'{pad}"""{lines[0]}"""']
    out = [f'{pad}"""{lines[0]}']
    for line in lines[1:]:
        out.append(f"{pad}{line}" if line else "")
    out.append(f'{pad}"""')
    return out


def method_signature(class_name, method_name, method):
    """Build ``def name(self, ...) -> type:`` from the text signature and METHOD_TYPES."""
    param_types, return_type = METHOD_TYPES[(class_name, method_name)]
    text_signature = method.__text_signature__  # e.g. "($self, flag)"
    names = [p.strip() for p in text_signature.strip("()").split(",") if p.strip()]
    if names[0] != "$self" or set(param_types) != set(names[1:]):
        raise ValueError(
            f"{class_name}.{method_name}: METHOD_TYPES does not match {text_signature}"
        )
    params = ["self"] + [f"{name}: {param_types[name]}" for name in names[1:]]
    return f"    def {method_name}({', '.join(params)}) -> {return_type}:"


def class_block(class_name):
    """Return the stub lines for one extension class."""
    cls = getattr(pyaga8, class_name)
    lines = [f"class {class_name}:"]
    lines += format_docstring(cls.__doc__, 4)
    lines += ["", "    def __init__(self) -> None: ..."]

    members = {name: value for name, value in vars(cls).items() if not name.startswith("_")}
    methods = sorted(name for name, value in members.items() if callable(value))
    properties = sorted(name for name in members if name not in methods)

    for name in methods:
        lines.append("")
        lines.append(method_signature(class_name, name, members[name]))
        lines += format_docstring(members[name].__doc__, 8)
        lines.append("        ...")

    for name in properties:
        lines.append("")
        if class_name == "Composition":
            # Write-only in the extension (setter only in src/lib.rs).
            lines.append(f"    {name}: float")
            lines += format_docstring(members[name].__doc__, 4)
            continue
        lines.append("    @property")
        lines.append(f"    def {name}(self) -> float:")
        lines += format_docstring(members[name].__doc__, 8)
        lines.append("        ...")
        if name in READ_WRITE_PROPERTIES:
            lines.append("")
            lines.append(f"    @{name}.setter")
            lines.append(f"    def {name}(self, value: float) -> None: ...")
    return lines


def generate():
    """Return the full stub text."""
    blocks = ["\n".join(class_block(name)) for name in CLASSES]
    return HEADER + "\n\n" + "\n\n\n".join(blocks) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate pyaga8.pyi")
    parser.add_argument("--check", action="store_true", help="only check, do not write")
    args = parser.parse_args(argv)
    text = generate()
    if args.check:
        current = STUB_PATH.read_text(encoding="utf-8").replace("\r\n", "\n")
        if current != text:
            print(f"{STUB_PATH.name} is out of date; run python tools/generate_stub.py")
            return 1
        print(f"{STUB_PATH.name} is up to date")
        return 0
    STUB_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {STUB_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
